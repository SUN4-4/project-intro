"""Regenerate website/assets/tasks.js from the per-benchmark tasks.json files.

    ~/RoboRSI/.venv/bin/python website/data/scripts/build_tasks_js.py

The main gallery is intentionally static JS so it works from a plain static
host (including GitHub Pages) without a fetch on first paint. LIBERO-Plus has
its own page and loads its 10,030-row catalog lazily.
"""

from __future__ import annotations

import json
from pathlib import Path

WEB_ROOT = Path(__file__).resolve().parents[2]
GROUPS = (
    ("libero", "LIBERO"),
    ("robotwin", "RoboTwin"),
    ("robosuite", "robosuite"),
    ("behavior", "BEHAVIOR-1K"),
)


def main() -> int:
    groups: list[dict] = []
    for benchmark, default_label in GROUPS:
        path = WEB_ROOT / "data" / benchmark / "tasks.json"
        payload = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(payload, list):
            tasks = payload
            label = default_label
        else:
            tasks = payload.get("tasks") or []
            label = payload.get("label") or default_label
        groups.append(
            {
                "benchmark": benchmark,
                "label": label,
                "dataDir": f"data/{benchmark}",
                "tasks": tasks,
            }
        )
    output = WEB_ROOT / "assets" / "tasks.js"
    body = json.dumps(groups, ensure_ascii=False, separators=(",", ":"))
    output.write_text(
        "// Generated by data/scripts/build_tasks_js.py; do not edit by hand.\n"
        f"window.BENCHMARK_TASKS = {body};\n",
        encoding="utf-8",
    )
    total = sum(len(group["tasks"]) for group in groups)
    print(f"wrote {output} with {len(groups)} groups and {total} tasks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
